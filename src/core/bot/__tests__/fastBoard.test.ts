import { describe, it, expect } from 'vitest';
import { createInitialGameState, getAllLegalMoves } from '../../schada/engine';
import type { Square } from '../../schada/types';
import { FastBoard } from '../fastBoard';
import { squareToIndex } from '../distanceTables';

describe('FastBoard Engine Symmetry & Move Generation', () => {
  it('round-trips between standard BoardMatrix and FastBoard with 100% fidelity', () => {
    const state = createInitialGameState();
    const fastBoard = FastBoard.fromBoardMatrix(state.board, state.currentTurn);
    const convertedBack = fastBoard.toBoardMatrix();

    for (const [sq, piece] of Object.entries(state.board)) {
      const convertedPiece = convertedBack[sq as Square];
      if (!piece) {
        expect(convertedPiece).toBeNull();
      } else {
        expect(convertedPiece).not.toBeNull();
        expect(convertedPiece?.type).toBe(piece.type);
        expect(convertedPiece?.color).toBe(piece.color);
        expect(convertedPiece?.hasLeftBase).toBe(piece.hasLeftBase);
        expect(convertedPiece?.hasReachedGoal).toBe(piece.hasReachedGoal);
      }
    }
  });

  it('matches all legal moves generated by standard engine on initial board', () => {
    const state = createInitialGameState();
    const engineMoves = getAllLegalMoves(state.board, 'white');

    const fastBoard = FastBoard.fromBoardMatrix(state.board, 'white');
    const fastMoves = fastBoard.generateLegalMoves('white');

    expect(fastMoves.length).toBe(engineMoves.length);

    const engineSignatures = new Set(engineMoves.map((m) => `${m.from}->${m.to}`));
    const fastSignatures = new Set(
      fastMoves.map((m) => {
        const std = fastBoard.toStandardMove(m);
        return `${std.from}->${std.to}`;
      })
    );

    expect(fastSignatures).toEqual(engineSignatures);
  });

  it('maintains perfect symmetry and state counts across makeMove and unmakeMove', () => {
    const state = createInitialGameState();
    const fastBoard = FastBoard.fromBoardMatrix(state.board, 'white');

    const initialWhiteTotal = fastBoard.whiteHighTotal;
    const initialBlackTotal = fastBoard.blackHighTotal;
    const legalMoves = fastBoard.generateLegalMoves('white');
    expect(legalMoves.length).toBeGreaterThan(0);

    const testMove = legalMoves[0];
    fastBoard.makeMove(testMove);

    expect(fastBoard.currentTurn).toBe('black');

    fastBoard.unmakeMove();

    expect(fastBoard.currentTurn).toBe('white');
    expect(fastBoard.whiteHighTotal).toBe(initialWhiteTotal);
    expect(fastBoard.blackHighTotal).toBe(initialBlackTotal);

    // Verify squares and flags are restored exactly
    const freshFast = FastBoard.fromBoardMatrix(state.board, 'white');
    for (let i = 0; i < 64; i++) {
      expect(fastBoard.squares[i]).toBe(freshFast.squares[i]);
      expect(fastBoard.flags[i]).toBe(freshFast.flags[i]);
    }
  });

  it('tracks high pieces in goal count when reaching goal line', () => {
    const fastBoard = new FastBoard();
    const e7Idx = squareToIndex('e7');
    const e8Idx = squareToIndex('e8'); // Goal rank for White (row 7)

    fastBoard.squares[e7Idx] = 2; // White Officer
    fastBoard.flags[e7Idx] = 1;   // hasLeftBase
    fastBoard.whiteHighTotal = 1;
    fastBoard.whiteHighInGoal = 0;

    const move = {
      from: e7Idx,
      to: e8Idx,
      piece: 2,
      captured: 0,
      intermediate: [],
    };

    fastBoard.makeMove(move);
    expect(fastBoard.whiteHighInGoal).toBe(1);
    expect(fastBoard.haveAllRemainingHighPiecesReachedGoal('white')).toBe(true);

    fastBoard.unmakeMove();
    expect(fastBoard.whiteHighInGoal).toBe(0);
    expect(fastBoard.haveAllRemainingHighPiecesReachedGoal('white')).toBe(false);
  });
});
